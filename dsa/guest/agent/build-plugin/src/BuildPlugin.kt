package io.github.thisisthepy.dsa.agent.build

import org.jetbrains.amper.plugins.Classpath
import org.jetbrains.amper.plugins.Input
import org.jetbrains.amper.plugins.Output
import org.jetbrains.amper.plugins.TaskAction
import java.io.File
import java.nio.file.Files
import java.nio.file.Path
import java.util.Properties
import java.util.zip.ZipEntry
import java.util.zip.ZipFile
import java.util.zip.ZipOutputStream
import kotlin.io.path.*

private val isWindows: Boolean = System.getProperty("os.name").lowercase().contains("win")

private fun exe(name: String): String = if (isWindows) "$name.exe" else name

private fun script(name: String): String = if (isWindows) "$name.bat" else name

private data class SdkPaths(
    val sdkRoot: Path,
    val buildToolsDir: Path,
    val androidJar: Path,
    val apiLevel: Int,
)

private fun parseVersionParts(version: String): List<Int> =
    version.split('.', '-', '_').map { it.toIntOrNull() ?: 0 }

private fun compareVersions(a: String, b: String): Int {
    val pa = parseVersionParts(a)
    val pb = parseVersionParts(b)
    val max = maxOf(pa.size, pb.size)
    for (i in 0 until max) {
        val cmp = (pa.getOrElse(i) { 0 }).compareTo(pb.getOrElse(i) { 0 })
        if (cmp != 0) return cmp
    }
    return a.compareTo(b)
}

private fun locateSdk(projectDir: Path): SdkPaths {
    val fromEnv = System.getenv("ANDROID_HOME")?.takeIf { it.isNotBlank() }
        ?: System.getenv("ANDROID_SDK_ROOT")?.takeIf { it.isNotBlank() }
    val fromLocalProps = (projectDir / "local.properties").takeIf { it.isRegularFile() }?.let { propFile ->
        Properties().apply { propFile.inputStream().use { load(it) } }.getProperty("sdk.dir")
    }
    val defaultPath = if (isWindows) {
        System.getenv("LOCALAPPDATA")?.let { "$it\\Android\\Sdk" }
    } else {
        listOf("/usr/local/lib/android/sdk", "${System.getProperty("user.home")}/Android/Sdk", "${System.getProperty("user.home")}/Library/Android/sdk")
            .firstOrNull { Path(it).isDirectory() }
    }
    val sdkPathStr = fromEnv ?: fromLocalProps ?: defaultPath
        ?: error("ANDROID_HOME (or ANDROID_SDK_ROOT) is not set and no Android SDK was found")
    val sdkRoot = Path(sdkPathStr)
    check(sdkRoot.isDirectory()) { "Android SDK directory does not exist: $sdkRoot" }

    val buildToolsRoot = sdkRoot / "build-tools"
    check(buildToolsRoot.isDirectory()) { "No build-tools directory in $sdkRoot" }
    val newestBuildTools = buildToolsRoot.listDirectoryEntries()
        .filter { it.isDirectory() }
        .maxWithOrNull { a, b -> compareVersions(a.name, b.name) }
        ?: error("No build-tools versions installed under $buildToolsRoot")

    val platformsRoot = sdkRoot / "platforms"
    check(platformsRoot.isDirectory()) { "No platforms directory in $sdkRoot" }
    val platformRegex = Regex("^android-(\\d+)$")
    val platforms = platformsRoot.listDirectoryEntries()
        .mapNotNull { dir ->
            val match = platformRegex.matchEntire(dir.name) ?: return@mapNotNull null
            val api = match.groupValues[1].toInt()
            val jar = dir / "android.jar"
            if (jar.isRegularFile()) Triple(api, dir, jar) else null
        }
        .sortedBy { it.first }
    check(platforms.isNotEmpty()) { "No android-<N> platforms installed under $platformsRoot" }
    val chosen = platforms.firstOrNull { it.first == 36 } ?: platforms.last()
    check(chosen.first >= 34) {
        "The newest installed Android platform is android-${chosen.first}; the agent needs API 34 or later"
    }
    return SdkPaths(
        sdkRoot = sdkRoot,
        buildToolsDir = newestBuildTools,
        androidJar = chosen.third,
        apiLevel = chosen.first,
    )
}

private fun runTool(command: List<String>, workingDir: Path? = null) {
    val pb = ProcessBuilder(command)
    if (workingDir != null) {
        pb.directory(workingDir.toFile())
    }
    pb.redirectErrorStream(true)
    val process = pb.start()
    val output = process.inputStream.bufferedReader().readText()
    val exit = process.waitFor()
    if (exit != 0) {
        error("Command failed with exit code $exit: ${command.joinToString(" ")}\n$output")
    }
}

/**
 * Generates the Java sources that the agent compiles against:
 * 1. The AIDL binder classes from `dsa/guest/aidl/` as a stable (VINTF) interface, with
 *    `this.markVintfStability();` redirected to `VintfStability.mark(this);`.
 * 2. The checked-in Java protobuf codec from `dsa/protocol/java/src/main/java`.
 * 3. `R.java` generated by `aapt2` from `src/main/res` and `src/main/AndroidManifest.xml`.
 */
@TaskAction
@OptIn(ExperimentalPathApi::class)
fun generateSources(
    @Input aidlDir: Path,
    @Input protocolJavaDir: Path,
    @Input resDir: Path,
    @Input manifestFile: Path,
    @Output outputDir: Path,
) {
    outputDir.deleteRecursively()
    outputDir.createDirectories()

    val projectDir = manifestFile.parent.parent.parent
    val sdk = locateSdk(projectDir)

    // 1. Generate AIDL Java stubs and point markVintfStability() at VintfStability.mark().
    val aidlFiles = aidlDir.walk()
        .filter { it.isRegularFile() && it.extension == "aidl" }
        .sortedBy { it.pathString }
        .toList()
    check(aidlFiles.isNotEmpty()) { "No AIDL files under $aidlDir" }

    val aidlExe = sdk.buildToolsDir / exe("aidl")
    runTool(
        listOf(
            aidlExe.absolutePathString(),
            "--lang=java",
            "--structured",
            "--stability=vintf",
            "--version=1",
            "-I", aidlDir.absolutePathString(),
            "-o", outputDir.absolutePathString(),
        ) + aidlFiles.map { it.absolutePathString() }
    )

    val call = "this.markVintfStability();"
    val replacement = "io.github.thisisthepy.dsa.agent.channel.VintfStability.mark(this);"
    outputDir.walk()
        .filter { it.isRegularFile() && it.extension == "java" }
        .forEach { file ->
            val text = file.readText()
            check(call in text) { "${file.name} no longer marks its stub stable; check the aidl output" }
            file.writeText(text.replace(call, replacement))
        }

    // 2. Copy the checked-in protocol Java sources so the module compiles them together.
    check(protocolJavaDir.isDirectory()) { "Protocol Java directory does not exist: $protocolJavaDir" }
    protocolJavaDir.walk()
        .filter { it.isRegularFile() && it.extension == "java" }
        .forEach { src ->
            val rel = src.relativeTo(protocolJavaDir)
            val dst = outputDir / rel
            dst.createParentDirectories()
            src.copyTo(dst, overwrite = true)
        }

    // 3. Compile resources and run aapt2 link with --java to produce R.java.
    val tempWork = Files.createTempDirectory("dsa-agent-aapt2")
    try {
        val compiledResZip = tempWork / "res.zip"
        val tempApk = tempWork / "res-only.apk"
        val aapt2Exe = sdk.buildToolsDir / exe("aapt2")
        runTool(
            listOf(
                aapt2Exe.absolutePathString(),
                "compile",
                "--dir", resDir.absolutePathString(),
                "-o", compiledResZip.absolutePathString(),
            )
        )
        runTool(
            listOf(
                aapt2Exe.absolutePathString(),
                "link",
                "-o", tempApk.absolutePathString(),
                "-I", sdk.androidJar.absolutePathString(),
                "--manifest", manifestFile.absolutePathString(),
                "--java", outputDir.absolutePathString(),
                "--min-sdk-version", sdk.apiLevel.toString(),
                "--target-sdk-version", sdk.apiLevel.toString(),
                "--version-code", "1",
                "--version-name", "0.1.0",
                compiledResZip.absolutePathString(),
            )
        )
    } finally {
        tempWork.deleteRecursively()
    }
}

/**
 * Packages the unsigned release APK using the Android SDK tools (`aapt2`, `d8`, `zipalign`)
 * directly, without Gradle.
 */
@TaskAction
@OptIn(ExperimentalPathApi::class)
fun packageApk(
    @Input runtimeClasspath: Classpath,
    @Input resDir: Path,
    @Input manifestFile: Path,
    @Output outputApk: Path,
) {
    val projectDir = manifestFile.parent.parent.parent
    val sdk = locateSdk(projectDir)

    val tempWork = Files.createTempDirectory("dsa-agent-package")
    try {
        val compiledResZip = tempWork / "res.zip"
        val unalignedApk = tempWork / "unaligned.apk"
        val dexDir = (tempWork / "dex").createDirectories()

        val aapt2Exe = sdk.buildToolsDir / exe("aapt2")
        runTool(
            listOf(
                aapt2Exe.absolutePathString(),
                "compile",
                "--dir", resDir.absolutePathString(),
                "-o", compiledResZip.absolutePathString(),
            )
        )
        runTool(
            listOf(
                aapt2Exe.absolutePathString(),
                "link",
                "-o", unalignedApk.absolutePathString(),
                "-I", sdk.androidJar.absolutePathString(),
                "--manifest", manifestFile.absolutePathString(),
                "--min-sdk-version", sdk.apiLevel.toString(),
                "--target-sdk-version", sdk.apiLevel.toString(),
                "--version-code", "1",
                "--version-name", "0.1.0",
                compiledResZip.absolutePathString(),
            )
        )

        val javaExe = Path(System.getProperty("java.home"), "bin", exe("java"))
        val d8Jar = sdk.buildToolsDir / "lib" / "d8.jar"
        val jars = runtimeClasspath.resolvedFiles.map { it.absolutePathString() }
        check(jars.isNotEmpty()) { "Runtime classpath for packageApk is empty" }
        runTool(
            listOf(
                javaExe.absolutePathString(),
                "-cp", d8Jar.absolutePathString(),
                "com.android.tools.r8.D8",
                "--release",
                "--min-api", sdk.apiLevel.toString(),
                "--lib", sdk.androidJar.absolutePathString(),
                "--output", dexDir.absolutePathString(),
            ) + jars
        )

        val dexFiles = dexDir.listDirectoryEntries("*.dex").sortedBy { it.name }
        check(dexFiles.isNotEmpty()) { "d8 produced no .dex files in $dexDir" }

        val mergedApk = tempWork / "merged.apk"
        ZipOutputStream(mergedApk.outputStream().buffered()).use { zos ->
            ZipFile(unalignedApk.toFile()).use { zip ->
                val entries = zip.entries()
                while (entries.hasMoreElements()) {
                    val entry = entries.nextElement()
                    val copy = ZipEntry(entry.name).apply {
                        method = entry.method
                        if (entry.method == ZipEntry.STORED) {
                            size = entry.size
                            compressedSize = entry.size
                            crc = entry.crc
                        }
                    }
                    zos.putNextEntry(copy)
                    zip.getInputStream(entry).use { it.copyTo(zos) }
                    zos.closeEntry()
                }
            }
            for (dex in dexFiles) {
                zos.putNextEntry(ZipEntry(dex.name))
                dex.inputStream().use { it.copyTo(zos) }
                zos.closeEntry()
            }
        }

        outputApk.createParentDirectories()
        outputApk.deleteIfExists()
        val zipalignExe = sdk.buildToolsDir / exe("zipalign")
        runTool(
            listOf(
                zipalignExe.absolutePathString(),
                "-f",
                "-p", "4",
                mergedApk.absolutePathString(),
                outputApk.absolutePathString(),
            )
        )
    } finally {
        tempWork.deleteRecursively()
    }
}
